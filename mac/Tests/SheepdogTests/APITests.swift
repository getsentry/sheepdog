@Test func streamSplitAcrossReadsGivesSameMessages() {
    var whole = SSEParser()
    let expected = whole.push(Data(streamText.utf8))
    // A two-byte character split between reads must stay intact.
    let bytes = Array("event: tasks\ndata: [\"Grüße\"]\n\n".utf8) + Array(streamText.utf8)
    for size in [1, 2, 7, 64] {
        var parser = SSEParser()
        var messages: [SSEMessage] = []
        for start in stride(from: 0, to: bytes.count, by: size) {
            messages += parser.push(bytes[start..<min(start + size, bytes.count)])
        }
        #expect(messages == [SSEMessage(event: "tasks", data: #"["Grüße"]"#)] + expected)
    }
}

